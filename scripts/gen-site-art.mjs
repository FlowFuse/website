#!/usr/bin/env node
// Regenerate nuxt/utils/siteArt.ts from the icon keys the site actually references.
//
// <SiteArt> inlines an SVG from src/_includes/components/icons/ verbatim, which is what
// page content that used a bare {% include %} needs. The registry is written out rather
// than globbed, so the bundle carries only the icons in use - an eager glob of that
// directory inlines ~137 KB, most of it unused art.
//
// Keeping it hand-maintained across ~50 keys is not realistic, so this scans for every
// key that is referenced and rewrites the file. Run it after adding a page that names a
// new icon; the build fails loudly on a missing import, and <SiteArt> warns in dev on a
// key the registry does not have.
//
// Usage: node scripts/gen-site-art.mjs [repo-root]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const ICON_DIR = 'src/_includes/components/icons'

function filesUnder (dir, ext) {
    if (!existsSync(dir)) return []
    return readdirSync(dir, { recursive: true, withFileTypes: true })
        .filter(entry => entry.isFile() && entry.name.endsWith(ext))
        .map(entry => join(entry.parentPath ?? entry.path, entry.name))
}

function matchAll (text, pattern) {
    return [...text.matchAll(pattern)].map(match => match[1])
}

// `explicit` are literal <SiteArt name="x" /> uses - a missing file there is a broken
// page, so it fails the run. `harvested` are svgPath:/icon: values in content and page
// consts, which a renderer *may* pass to SiteArt but may equally resolve some other way
// (contact-us has its own icon map, for one), so a miss there is only reported.
function referencedKeys (root) {
    const vues = [...filesUnder(join(root, 'nuxt/pages'), '.vue'), ...filesUnder(join(root, 'nuxt/components'), '.vue')]
    const explicit = new Set()
    for (const file of vues) {
        for (const key of matchAll(readFileSync(file, 'utf8'), /<SiteArt\s+name="([a-z0-9-]+)"/g)) explicit.add(key)
    }
    // svgPath:/icon: keys in the content collections, which the renderers pass to SiteArt,
    // and the same keys declared in a page's own const arrays. Both quote styles: YAML
    // here is double-quoted, the .vue consts are single-quoted.
    const harvested = new Set()
    for (const file of [...filesUnder(join(root, 'nuxt/content'), '.yml'), ...vues]) {
        for (const key of matchAll(readFileSync(file, 'utf8'), /(?:svgPath|icon|eyebrowIcon|badge):\s*["']([a-z0-9-]+)["']/g)) {
            // An "i-heroicons-x" / "i-lucide-x" value is a <UIcon> name resolved from an
            // installed icon set, not a file in this repo, so it is not SiteArt's to provide.
            if (!key.startsWith('i-')) harvested.add(key)
        }
    }
    return { explicit, harvested }
}

const ident = key => 'a' + key.split('-').map(part => part.charAt(0).toUpperCase() + part.slice(1)).join('')

const HEADER = `// SVG files that page content included raw, with no wrapper: {% include "components/icons/
// x.svg" %} rather than the \`navoption\`/\`ffIconLg\` shortcodes that NavIcon reproduces.
//
// They cannot go through NavIcon or an <img>:
//  - NavIcon wraps its payload in an outer <svg> carrying a fixed ff-icon size class,
//    which would override the size the caller's box sets.
//  - <img> breaks \`currentColor\`, and most of these are coloured by their container.
//
// GENERATED by scripts/gen-site-art.mjs from the keys the pages and content collections
// actually reference, so the bundle carries only what is used - an eager glob of that
// directory inlines ~137 KB, most of it unused art. Re-run it after adding a page that
// names a new icon.
`

const root = resolve(process.argv[2] ?? '.')
const { explicit, harvested } = referencedKeys(root)

// Keys that resolve through NavIcon (the navoption/ffIconLg wrapper) or a hand-written
// Vue icon component are not SiteArt's job.
const navFile = join(root, 'nuxt/utils/navIcons.ts')
const navKeys = existsSync(navFile) ? new Set(matchAll(readFileSync(navFile, 'utf8'), /^ {4}'([a-z0-9-]+)':/gm)) : new Set()

const usable = []
const missing = []
for (const key of [...new Set([...explicit, ...harvested])].sort()) {
    (existsSync(join(root, ICON_DIR, `${key}.svg`)) ? usable : missing).push(key)
}

const lines = [HEADER]
for (const key of usable) lines.push(`import ${ident(key)} from '../../${ICON_DIR}/${key}.svg?raw'`)
lines.push('\nexport const siteArt: Record<string, string> = {')
for (const key of usable) lines.push(`    '${key}': ${ident(key)},`)
lines.push('}\n')

const out = join(root, 'nuxt/utils/siteArt.ts')
writeFileSync(out, lines.join('\n'))
console.log(`${out}: ${usable.length} icons`)

const alsoInNav = usable.filter(key => navKeys.has(key))
if (alsoInNav.length) console.log(`  (also in navIcons, which is fine - different wrapper: ${alsoInNav.slice(0, 6).join(', ')}…)`)
if (missing.length) console.log(`  no SVG file (resolved elsewhere, not bundled here): ${missing.join(', ')}`)

const broken = missing.filter(key => explicit.has(key))
if (broken.length) {
    console.log(`  ERROR: <SiteArt> is asked for these and there is no file: ${broken.join(', ')}`)
    process.exit(1)
}
